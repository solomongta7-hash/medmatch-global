/* Result Preview — app shell.

   Flow: pick a treatment, frame a face, capture, then drag sliders and
   compare against the untouched photo. The camera is only unlocked once
   the model can actually see a usable face, because every one of these
   simulations degrades badly on a three-quarter view and it is far
   cheaper to nag before the shutter than to apologise after it. */

