async function startCamera() {
  show("s-cam");
  $("#boot").hidden = false;
  $("#boot").style.display = "";
  shoot.disabled = true;

  try {
    await initFace();
  } catch (e) {
    bootError("Could not load the face model. Reload the page and try again.");
    return;
  }

  try {
    state.stream = await navigator.mediaDevices.getUserMedia({
      video: { facingMode: state.facing, width: { ideal: 1280 }, height: { ideal: 1280 } },
      audio: false
    });
  } catch (e) {
    bootError(
      "No camera access. You can still upload a photo from your gallery.",
      true
    );
    return;
  }

  video.srcObject = state.stream;
  await video.play().catch(() => {});
  $("#boot").style.display = "none";
  video.style.transform = state.facing === "user" ? "scaleX(-1)" : "none";
  loop();
}

function bootError(msg, allowUpload) {
  const b = $("#boot");
  b.style.display = "";
  b.innerHTML = `<div><p class="boot__err">${msg}</p>${
    allowUpload ? '<button id="boot-up">Choose a photo</button>' : ""
  }</div>`;
  const up = document.getElementById("boot-up");
  if (up) up.addEventListener("click", () => $("#file").click());
}

function stopCamera() {
  cancelAnimationFrame(state.raf);
  if (state.stream) {
    state.stream.getTracks().forEach(t => t.stop());
    state.stream = null;
  }
}

