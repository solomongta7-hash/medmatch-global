/* So dragging renders a smaller copy and the full one is produced when
   the finger lifts. The warp cost is per-pixel, so this is the
   difference between roughly 8fps and roughly 25fps on a mid-range
   phone, on the one interaction the whole tool is built around. The
   draft is only ever a backing-store change: both canvases are stretched
   to the same box by CSS, so the divider still lines up exactly. */
const DRAFT_MAX = 520;

