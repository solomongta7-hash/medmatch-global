# ── build ─────────────────────────────────────────────────────────────────
src = os.path.join(ROOT, "tools", "_book-strings.json")
if not os.path.exists(src):
    sys.exit("Run the two collector scripts first - see the header.")

english = json.load(io.open(src, encoding="utf-8"))
tables = {"es": ES, "fr": FR, "de": DE, "tr": TR}

for code, arr in tables.items():
    if len(arr) != len(english):
        sys.exit("%s has %d translations for %d English strings. book.html changed - "
                 "re-run the collectors and fix the list." % (code, len(arr), len(english)))

merged = {en: {c: tables[c][i] for c in LANGS} for i, en in enumerate(english)}

io.open(os.path.join(ROOT, "tools", "book-i18n.json"), "w", encoding="utf-8").write(
    json.dumps(merged, ensure_ascii=False, indent=1))

added_total = 0
for code in LANGS:
    path = os.path.join(ROOT, "js", "lang", "%s.js" % code)
    s = io.open(path, encoding="utf-8").read()
    tail = s.rstrip()
    if not tail.endswith("});"):
        sys.exit("%s.js does not end with the expected registerText block." % code)

    lines = []
    for en, row in merged.items():
        key = json.dumps(en, ensure_ascii=False)
        if key + ":" in s:
            continue
        lines.append("%s:%s" % (key, json.dumps(row[code], ensure_ascii=False)))
    if not lines:
        print("%s: already complete" % code)
        continue

    body = tail[:-3].rstrip()
    if not body.endswith(","):
        body += ","
    io.open(path, "w", encoding="utf-8", newline="").write(
        body + "\n" + ",\n".join(lines) + "\n});\n")
    print("%s: added %d book strings" % (code, len(lines)))
    added_total += len(lines)

print("Done - %d entries added across %d languages." % (added_total, len(LANGS)))
